type Piece = { text: string; page: number | null };
type Section = { text: string; page: number | null };

const splitter = new RecursiveCharacterTextSplitter({
  chunkSize: 1000,
  chunkOverlap: 150,
  separators: ["\n\n", "\n", ". ", " "],
});

function cleanPdf(text: string): string {
  return text
    .replace(/\u00a0/g, " ")
    .replace(/[ \t]+$/gm, "")
    .replace(/^\d{1,2}\/\d{1,2}$/gm, "") // page counters like "2/4"
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

// footers and headers repeat on every page; drop lines found on 3+ pages
function stripRepeated(pages: string[]): string[] {
  const seen = new Map<string, number>();
  for (const p of pages) {
    for (const l of new Set(p.split("\n").map((s) => s.trim()))) {
      if (l.length > 10) seen.set(l, (seen.get(l) ?? 0) + 1);
    }
  }
  const repeated = new Set(
    [...seen].filter(([, n]) => n >= 3 && pages.length >= 3).map(([l]) => l),
  );
  return pages.map((p) =>
    p.split("\n").filter((l) => !repeated.has(l.trim())).join("\n"),
  );
}

// pdf syllabus: sections start at "3. Entry requirements" or "Semester 2"
function pdfSections(raw: string): Section[] {
  const parts = raw.split(/=== PAGE (\d+) ===\n/);
  const nums: number[] = [];
  const texts: string[] = [];
  for (let i = 1; i < parts.length; i += 2) {
    nums.push(Number(parts[i]));
    texts.push(cleanPdf(parts[i + 1]));
  }
  const pages = stripRepeated(texts);

  let full = "";
  const starts: { page: number; offset: number }[] = [];
  pages.forEach((t, i) => {
    starts.push({ page: nums[i], offset: full.length });
    full += t + "\n";
  });
  const pageAt = (o: number) => starts.filter((s) => s.offset <= o).at(-1)!.page;

  const out: Section[] = [];
  let offset = 0;
  for (const s of full.split(/^(?=\d{1,2}\. [A-Z]|Semester \d)/m)) {
    out.push({ text: s, page: pageAt(offset) });
    offset += s.length;
  }
  return out;
}

// html text from the scraper has "#", "##", "###" headings
function htmlSections(raw: string): Section[] {
  return raw.split(/^(?=#{1,3} )/m).map((s) => ({ text: s, page: null }));
}

async function toPieces(sections: Section[]): Promise<Piece[]> {
  const out: Piece[] = [];
  let carry = ""; // a heading with no text of its own waits for the next section
  for (const s of sections) {
    const body = s.text.trim();
    if (!body) continue;
    const hasBody = body.split("\n").slice(1).join("").trim().length > 20;
    if (!hasBody) {
      carry = carry ? `${carry}\n${body}` : body;
      continue;
    }
    const text = carry ? `${carry}\n${body}` : body;
    carry = "";
    if (text.length <= MAX_CHUNK) {
      out.push({ text, page: s.page });
      continue;
    }
    const title = text.split("\n")[0].trim();
    for (const sub of await splitter.splitText(text)) {
      out.push({ text: sub.startsWith(title) ? sub : `${title}\n${sub}`, page: s.page });
    }
  }
  if (carry) out.push({ text: carry, page: null });
  return out;
}

const points: any[] = [];

async function addPieces(
  programme: any,
  sourceType: string,
  sourceUrl: string,
  pieces: Piece[],
) {
  const label = sourceType === "syllabus" ? "programme syllabus" : "programme web page";
  for (const [i, piece] of pieces.entries()) {
    points.push({
      id: uuidv4(),
      // the programme name goes into the embedded text so that
      // "Computer Science" in a question pulls the right chunks
      vector: await embed(`${programme.name} (${programme.code}), ${label}\n${piece.text}`),
      payload: {
        text: piece.text,
        programme_code: programme.code,
        programme_name: programme.name,
        source_type: sourceType,
        page: piece.page,
        source_url: sourceUrl,
        chunk_index: i,
      },
    });
  }
  console.log(`${programme.code} | ${sourceType} | ${pieces.length} chunks`);
}

for (const p of programmes) {
  const dir = new URL(`programmes/${p.code.toLowerCase()}/`, dataDir);
  const meta = JSON.parse((await tryRead(new URL("metadata.json", dir))) ?? "{}");

  const syllabus = await tryRead(new URL("syllabus.txt", dir));
  if (syllabus) {
    const sections = meta.syllabus_format === "pdf" ? pdfSections(syllabus) : htmlSections(syllabus);
    await addPieces(p, "syllabus", meta.syllabus_url, await toPieces(sections));
  }
  const page = await tryRead(new URL("programme_page.txt", dir));
  if (page) {
    await addPieces(p, "programme_page", p.url, await toPieces(htmlSections(page)));
  }
}

